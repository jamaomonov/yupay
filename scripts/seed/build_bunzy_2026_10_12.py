"""Generate the review SQL for the seven Bunzy drafts of 2026-10-06 … 10-12.

One SQL file per post, `scripts/seed/2026-10-12_blog_<name>.sql`, from the
content modules in `scripts/seed/bunzy_2026_10_12/`. Every body is rendered
through the API's own ``markdown_to_html`` + ``sanitize_body``, so what the
seed stores is byte-for-byte what the admin editor would have stored (see
`build_steam_gifts_post.py` for why hand-written HTML is not an option).

Each SQL: brand + cover on the post, then delete-and-insert of all three
translations and their FAQs — so a re-run replaces, never duplicates.
Unlike the 10-05 batch, the owner asked for these to go out one a day: each
module carries ``publish_at`` and the SQL sets ``status = 'scheduled'`` with
that ``scheduled_for``. The scheduler's ``blog.publish_due`` job publishes it
through ``admin_service.publish_post`` (sanitize, pin cap, IndexNow) — the
same path as the admin's «Запланировать» button.

Internal links are written locale-neutral in the modules (`/store/...`,
`/blog/<that-locale's-slug>`); the English and Uzbek bodies get their
`/en` / `/uz` prefix here, the way every published post links.

Run from the repo root:

    uv run python scripts/seed/build_bunzy_2026_10_12.py

Regenerate and re-commit the .sql files whenever the copy changes; never
edit a generated file by hand.
"""

from __future__ import annotations

import importlib
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "apps" / "api" / "src"))
sys.path.insert(0, str(REPO / "scripts" / "seed"))

from yupay.modules.blog.markdown_html import markdown_to_html  # noqa: E402
from yupay.modules.blog.sanitize import sanitize_body  # noqa: E402

MEDIA_BASE = "https://media.yupay.uz"
MODULES = (
    "yupay_vs",
    "honkai_star_rail",
    "package_size",
    "arena_breakout",
    "fast_topup",
    "telegram_stars",
    "subscriptions",
)
CAPS = {"title": 200, "excerpt": 280, "seo_title": 200, "seo_description": 320}
_LINK = re.compile(r"\]\((/(?:store|blog)[^)]*)\)")


def body(markdown: str, locale: str) -> str:
    if locale != "ru":
        markdown = _LINK.sub(lambda m: f"](/{locale}{m.group(1)})", markdown)
    result = markdown_to_html(markdown.strip() + "\n")
    if result.dropped_images or result.unwrapped_links or result.demoted_headings:
        raise SystemExit(
            f"copy uses constructs the allowlist drops: {result.dropped_images} images, "
            f"{result.unwrapped_links} links, {result.demoted_headings} headings"
        )
    return sanitize_body(result.html, media_base_url=MEDIA_BASE, allow_empty=False)


def q(text: str) -> str:
    if "$x$" in text:
        raise SystemExit("copy contains the dollar-quote tag")
    return f"$x${text}$x$"


def render(name: str) -> Path:
    mod = importlib.import_module(f"bunzy_2026_10_12.{name}")
    post = mod.POST
    pid = post["post_id"]
    header = [
        line if line else "--"
        for line in ("-- " + ln if ln else "" for ln in mod.__doc__.strip().splitlines())
    ]
    out = [
        f"-- scripts/seed/2026-10-12_blog_{name}.sql",
        "--",
        "-- GENERATED by scripts/seed/build_bunzy_2026_10_12.py — do not edit by hand.",
        "--",
        *header,
        "",
        "BEGIN;",
        "",
        f"\\set post_id '''{pid}'''",
        "",
        "UPDATE blog_posts",
        f"SET primary_brand_id = (SELECT id FROM brands WHERE slug = '{post['brand_slug']}'),",
        f"    cover_image_url = '{post['cover']}',",
        "    status = 'scheduled',",
        f"    scheduled_for = '{post['publish_at']}',",
        "    updated_at = now()",
        "WHERE id = :post_id AND status IN ('draft', 'scheduled');",
        "",
        "DELETE FROM blog_post_translations WHERE post_id = :post_id;",
        "DELETE FROM blog_post_faqs WHERE post_id = :post_id;",
        "",
    ]
    for locale, label in (("ru", "Russian"), ("en", "English"), ("uz", "Uzbek")):
        t = post[locale]
        for field, cap in CAPS.items():
            if len(t[field]) > cap:
                raise SystemExit(f"{name}.{locale}.{field} is {len(t[field])} chars, cap is {cap}")
        out += [
            f"-- {'-' * (64 - len(label))} {label} --",
            "",
            "INSERT INTO blog_post_translations",
            "  (post_id, locale, slug, title, excerpt, body_html, seo_title, seo_description)",
            "VALUES (",
            f"  :post_id, '{locale}', {q(t['slug'])},",
            f"  {q(t['title'])},",
            f"  {q(t['excerpt'])},",
            f"{q(body(t['body'], locale))},",
            f"  {q(t['seo_title'])},",
            f"  {q(t['seo_description'])}",
            ");",
            "",
            "INSERT INTO blog_post_faqs (id, post_id, locale, sort_order, question, answer) VALUES",
            ",\n".join(
                f"(gen_random_uuid(), :post_id, '{locale}', {i}, {q(question)},\n {q(answer)})"
                for i, (question, answer) in enumerate(t["faqs"])
            )
            + ";",
            "",
        ]
    out += ["COMMIT;", ""]
    target = REPO / "scripts" / "seed" / f"2026-10-12_blog_{name}.sql"
    target.write_text("\n".join(out), encoding="utf-8")
    return target


def main() -> None:
    for name in MODULES:
        target = render(name)
        print(f"wrote {target.relative_to(REPO)}")


if __name__ == "__main__":
    main()
